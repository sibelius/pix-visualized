  lcl: "LclInstrm/Prtry = AUTO (formaDeIniciacao). In the pain.013 it sits in PmtTpInf; in the pacs.008 in MndtRltdInf/Tp. Mandatory AUTO even when an ITP initiated it through Open Finance with MANU on its own API.",
