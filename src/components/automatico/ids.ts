/**
 * Identifiers of Pix Automático, implemented from their formation rules:
 *  - idRec        (API Pix `RecId`, pain.009/012/013 `MndtId`): [R|C][R|N] + agent(8) + yyyyMMdd + seq(11) = 29 chars
 *  - idSolicRec   (API Pix `SolicRecId`): "SC" + ISPB(8) + yyyyMMdd + seq(11) = 29 chars
 *  - EndToEndId   (pain.013 `idFimAFim`, reused by the pacs.008): "E" + receiver-side ISPB(8) + yyyyMMddHHmm (UTC) + seq(11)
 */

export const ID_REC_RE = /^[RC][RN][0-9A-Z]{8}[0-9]{4}[0-1][0-9][0-3][0-9][a-zA-Z0-9]{11}$/;
export const ID_SOLIC_RE = /^SC[0-9A-Z]{8}[0-9]{4}[0-1][0-9][0-3][0-9][a-zA-Z0-9]{11}$/;
export const E2E_RE = /^E[0-9A-Z]{8}[0-9]{4}[0-1][0-9][0-3][0-9][0-2][0-9][0-5][0-9][a-zA-Z0-9]{11}$/;

const ALNUM = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

/** Deterministic 11-char sequential from a counter (base-62, left-padded). */
export function seq11(n: number): string {
  let s = "";
  let x = Math.max(0, Math.floor(n));
  do {
    s = ALNUM[x % 62] + s;
    x = Math.floor(x / 62);
  } while (x > 0);
  return s.padStart(11, "0").slice(-11);
}

export function buildIdRec(opts: { openFinance: boolean; retries: boolean; agent: string; date: string; seq: string }) {
  return `${opts.openFinance ? "C" : "R"}${opts.retries ? "R" : "N"}${opts.agent}${opts.date}${opts.seq}`;
}

export type Part = { label: string; value: string; ok: boolean; note: string };

/** Break an idRec into its parts and validate each one. */
export function parseIdRec(id: string): { parts: Part[]; ok: boolean } {
  const s = id;
  const date = s.slice(10, 18);
  const y = Number(date.slice(0, 4));
  const m = Number(date.slice(4, 6));
  const d = Number(date.slice(6, 8));
  const dateOk = /^\d{8}$/.test(date) && m >= 1 && m <= 12 && d >= 1 && d <= new Date(Date.UTC(y, m, 0)).getUTCDate();
  const parts: Part[] = [
    {
      label: "origin",
      value: s.slice(0, 1),
      ok: /^[RC]$/.test(s.slice(0, 1)),
      note: s[0] === "C" ? "C = created through Open Finance (an ITP)" : "R = created inside Pix (receiver PSP)",
    },
    {
      label: "retries",
      value: s.slice(1, 2),
      ok: /^[RN]$/.test(s.slice(1, 2)),
      note: s[1] === "R" ? "R = retries after the due date allowed (PERMITE_3R_7D)" : "N = no retries after due date (NAO_PERMITE)",
    },
    {
      label: "agent",
      value: s.slice(2, 10),
      ok: /^[0-9A-Z]{8}$/.test(s.slice(2, 10)),
      note: "ISPB of the direct/indirect participant, or first 8 chars of the ITP's CNPJ ([0-9A-Z]{8})",
    },
    { label: "yyyyMMdd", value: date, ok: dateOk, note: "creation date of the recorrência (Brasília calendar date)" },
    {
      label: "sequence",
      value: s.slice(18, 29),
      ok: /^[a-zA-Z0-9]{11}$/.test(s.slice(18, 29)),
      note: "11 alphanumerics, unique per agent per day; case-sensitive",
    },
  ];
  return { parts, ok: s.length === 29 && parts.every((p) => p.ok) };
}

/**
 * EndToEndId of a Pix Automático instruction. Unlike a normal Pix (generated by the payer side), here the RECEIVER PSP
 * generates it in the pain.013, using the scheduled settlement date and a fixed 15:00 UTC, which the SPI accepts with a
 * ±12h tolerance — so the payer PSP may settle any time between 00:00 and 23:59 Brasília on that date.
 */
export function e2eAuto(receiverIspb: string, settleDate: string, n: number) {
  return `E${receiverIspb}${settleDate}1500${seq11(n)}`;
}
